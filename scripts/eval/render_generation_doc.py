# ruff: noqa: E501  (markdown table rows are kept on one line each)
"""Render the "Generation" section of docs/BENCHMARKS.md from scripts/eval/results/generation.json.

Everything from the "## Generation" heading to the end of the file is replaced, so the section is
always a pure function of the committed result file. Usage: python scripts/eval/render_generation_doc.py
"""

from __future__ import annotations

import json
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DOC = REPO / "docs" / "BENCHMARKS.md"
RESULT = Path(__file__).parent / "results" / "generation.json"


def _pct(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:.1f}%"


def _ms(x: float | None) -> str:
    return "n/a" if x is None else f"{x / 1000:.2f} s"


def render(data: dict) -> str:
    s = data["summary"]
    rows = data["rows"]
    pos = [r for r in rows if r["kind"] == "pos"]
    neg = [r for r in rows if r["kind"] == "neg"]
    answered = [r for r in pos if not r["abstained"]]
    judged = [r for r in answered if "faithful" in r]
    n_faithful = sum(r["faithful"] for r in judged)
    n_correct = sum(r["correct"] for r in judged)
    n_cited_gold = sum(r["cited_gold"] for r in answered)
    neg_abst = sum(r["abstained"] for r in neg)
    pos_abst = sum(r["abstained"] for r in pos)
    unfaithful = [r for r in judged if not r["faithful"]]
    incorrect = [r for r in judged if not r["correct"]]
    missed_neg = [r for r in neg if not r["abstained"]]
    false_abst = [r for r in pos if r["abstained"]]

    out = [
        "## Generation",
        "",
        "Generated by `python scripts/eval/render_generation_doc.py` from `scripts/eval/results/generation.json`",
        "(written by `python scripts/eval/run_generation.py report`; one row per question in",
        "`scripts/eval/results/rows/gen__*.json`). Nothing here is estimated.",
        "",
        "Pipeline: production defaults (parent-child chunks, hybrid RRF + cross-encoder rerank, parent",
        "expansion, streaming generation) on the live Groq API. Answerable questions use document scope (the",
        "question's own document selected, as in the app); negatives use corpus scope (all 8 documents).",
        "",
        "| | |",
        "|---|---|",
        f"| Answer model | `{s['answer_model']}` |",
        f"| Judge model | `{s['judge_model']}` (same model as the answerer, see limitations) |",
        f"| Answerable questions | {s['answerable_questions']} |",
        f"| Out-of-scope negatives | {s['negatives']} |",
        f"| Answered (not abstained) | {len(answered)} of {len(pos)} |",
        f"| Judged by the LLM judge | {len(judged)} |",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| Faithfulness (judge: every claim supported by the sources) | **{_pct(s['faithfulness'])}** ({n_faithful}/{len(judged)}) |",
        f"| Answer correctness vs golden (judge), over answered | **{_pct(s['correctness'])}** ({n_correct}/{len(judged)}) |",
        f"| Answer correctness over all answerable (abstain = wrong) | {_pct(s['correct_over_all_answerable'])} |",
        f"| Gold-cited rate (answer cites a source holding the gold evidence) | **{_pct(s['gold_cited_rate'])}** ({n_cited_gold}/{len(answered)}) |",
        f"| Citation precision (cited sources holding the gold evidence; strict lower bound) | {_pct(s['citation_precision'])} |",
        f"| Answers with no citation | {s['answers_without_citations']} |",
        f"| Gold evidence in the context given to the model | {_pct(s['gold_in_context_rate'])} |",
        f"| Abstention recall (negatives that abstained) | **{_pct(s['abstention_recall'])}** ({neg_abst}/{len(neg)}) |",
        f"| Abstention precision (abstentions that were negatives) | **{_pct(s['abstention_precision'])}** ({neg_abst}/{neg_abst + pos_abst}) |",
        f"| False abstention rate (answerable questions that abstained) | {_pct(s['false_abstention_rate'])} ({pos_abst}/{len(pos)}) |",
        f"| TTFT p50 / p95 (incl. retrieval), all {s['latency_rows']} generated rows | {_ms(s['ttft_ms_p50'])} / {_ms(s['ttft_ms_p95'])} |",
        f"| End-to-end p50 / p95, all generated rows | {_ms(s['e2e_ms_p50'])} / {_ms(s['e2e_ms_p95'])} |",
        f"| TTFT p50 / p95, rows without rate-limit retries ({s['latency_rows'] - s['latency_rows_with_rate_limit_retries']}) | {_ms(s['ttft_ms_p50_no_retries'])} / {_ms(s['ttft_ms_p95_no_retries'])} |",
        f"| End-to-end p50 / p95, rows without rate-limit retries | {_ms(s['e2e_ms_p50_no_retries'])} / {_ms(s['e2e_ms_p95_no_retries'])} |",
        "",
        "### Misses",
        "",
    ]
    for label, items in (
        ("Judged unfaithful", unfaithful),
        ("Judged incorrect", incorrect),
        ("Negatives answered instead of abstaining", missed_neg),
        ("Answerable questions that abstained", false_abst),
    ):
        ids = ", ".join(f"`{r['qid']}`" for r in items) or "none"
        out.append(f"- {label}: {ids}")
    out += [
        "",
        "### Limitations",
        "",
        "- The judge is the answer model judging its own answers (the script's default), which can be lenient;",
        "  verdicts are single-sample at temperature 0 and were not hand-audited.",
        "- Faithfulness is judged against all sources given to the model, not claim-by-claim against the",
        "  specific `[S#]` each claim cites. Citation precision only credits sources that contain the gold",
        "  evidence span, so a citation to a non-gold source that does support its claim counts as wrong.",
        "- Small sample: 26 questions on the Arca contract, 10 on `alpha_contract.pdf`, 2 on Pelican; differences of",
        "  a few points are noise.",
        "- The config default `GROQ_MODEL=llama-3.3-70b-versatile` returned 404 `model_not_found` for the eval",
        "  key on 2026-11-03, so the run set `GROQ_MODEL` to the model above.",
        "- Latency is from one sandbox to the Groq free tier and includes retrieval (embedding + rerank on CPU).",
        "  Rows where a 429 back-off happened during the answer stream are counted separately.",
        "",
        "Reproduce: `python scripts/eval/fetch_corpus.py`, `python scripts/eval/run_retrieval.py ingest --strategy",
        "parent_child`, then `GROQ_API_KEY=... python scripts/eval/run_generation.py run` (resumable) and",
        "`python scripts/eval/render_generation_doc.py`.",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    data = json.loads(RESULT.read_text())
    text = DOC.read_text()
    head = text.split("\n## Generation", 1)[0].rstrip("\n")
    DOC.write_text(head + "\n\n" + render(data))
    print(f"updated {DOC}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
